// Generate src/scenes/spine-files.ts: every spine step's project files, as the explorer draws them.
// Scenes cannot list a folder (the checks bundle them with esbuild, which has no glob), so the list
// is written here from the spine itself. Run after --write / --record: `node scripts/spine-files.mjs`.
import { readdirSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const IGNORED = new Set(['__pycache__', '.venv', 'data', 'out', '.terraform', 'terraform.tfstate', 'terraform.tfstate.backup', 'tfplan'])
const walk = (dir, prefix = '') => readdirSync(dir).sort().flatMap((name) => {
  if (IGNORED.has(name)) return []
  const path = join(dir, name)
  return statSync(path).isDirectory() ? walk(path, `${prefix}${name}/`) : [`${prefix}${name}`]
})
const out = {}
for (const course of readdirSync('spine').sort())
  for (const step of readdirSync(join('spine', course)).sort())
    out[`${course}/${step}`] = walk(join('spine', course, step, 'project'))
writeFileSync('src/scenes/spine-files.ts', `// GENERATED by scripts/spine-files.mjs from spine/*/*/project — do not edit.\nexport const SPINE_FILES: Record<string, string[]> = ${JSON.stringify(out, null, 1)}\n`)
console.log(`src/scenes/spine-files.ts: ${Object.keys(out).length} steps`)
