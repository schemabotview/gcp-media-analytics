"""Write Sun's source data.

  python -m sun_gen --out data                  everything
  python -m sun_gen --out data --part crm       one part
  python -m sun_gen verify                      assert every planted fact

Same seed → byte-identical files. Layout under --out:

  crm/packages.csv, households.csv, subscriptions.csv   the CRM at SEED_CUTOFF (00:00, 31 October)
  crm/day-2026-10-31.sql        the CRM's business day: the derby-day Sports upgrades
  billing/charges.csv           billing at SEED_CUTOFF: every charge posted 28-30 October
  billing/day-2026-10-31.sql    billing's business day: the 31st's charges, as its application posted them
  billing/rerate.sql            §5.5: three charges re-rated at 02:00:04 on 1 November, during the copy
  catalogue/titles.csv          the content catalogue, as the vendor delivers it
  epg/2026-10-31.json           the electronic programme guide for derby day, as the vendor delivers it
"""
from __future__ import annotations

import argparse
import csv
import io
import json
import sys
from decimal import Decimal
from pathlib import Path

from .model import BUSINESS_DATE, PACKAGES, RERATE_AT, RERATE_CREDIT, SEED_CUTOFF, build

PARTS = ('crm', 'billing', 'catalogue', 'epg')


def ts(t) -> str:
    return t.strftime('%Y-%m-%d %H:%M:%S+00')


def csv_text(rows: list[dict]) -> str:
    buf = io.StringIO(newline='')
    w = csv.DictWriter(buf, fieldnames=list(rows[0]), lineterminator='\n')
    w.writeheader()
    w.writerows(rows)
    return buf.getvalue()


def lit(v) -> str:
    if v is None:
        return 'NULL'
    return str(v) if isinstance(v, (int, Decimal)) else "'" + str(v).replace("'", "''") + "'"


def files(part: str) -> dict[str, str]:
    w = build()
    if part == 'crm':
        def row(s, valid_to, updated_at):
            return {'subscription_id': s.subscription_id, 'household_id': s.household_id, 'package_id': s.package_id,
                    'valid_from': s.valid_from.isoformat(), 'valid_to': valid_to.isoformat() if valid_to else '',
                    'updated_at': ts(updated_at)}
        seed = [row(s, None, w.before[s.subscription_id]) if s.subscription_id in w.before else row(s, s.valid_to, s.updated_at)
                for s in w.subscriptions if s.updated_at <= SEED_CUTOFF or s.subscription_id in w.before]
        day = ['-- The CRM\'s business day, 2026-10-31: derby-day Sports upgrades, as the CRM application made',
               '-- them. Generated by sun_gen; applied before Course 5 lands dt=2026-10-31.', 'BEGIN;']
        for s in sorted((s for s in w.subscriptions if s.updated_at > SEED_CUTOFF), key=lambda s: (s.updated_at, s.subscription_id)):
            if s.subscription_id in w.before:
                day.append(f"UPDATE subscriptions SET valid_to = '{s.valid_to}', updated_at = '{ts(s.updated_at)}' "
                           f"WHERE subscription_id = '{s.subscription_id}';")
            else:
                vals = [s.subscription_id, s.household_id, s.package_id, s.valid_from.isoformat(), None, ts(s.updated_at)]
                day.append(f'INSERT INTO subscriptions VALUES ({", ".join(map(lit, vals))});')
        day.append('COMMIT;')
        return {
            'packages.csv': csv_text([{'package_id': p, 'name': n, 'monthly_price': f'{a:.2f}'} for p, n, a in PACKAGES]),
            'households.csv': csv_text([{'household_id': h.household_id, 'first_name': h.first, 'last_name': h.last,
                                         'email': h.email, 'phone': h.phone, 'postcode': h.postcode, 'region': h.region,
                                         'exchange_id': h.exchange_id, 'bill_day': h.bill_day, 'joined_at': ts(h.joined_at),
                                         'updated_at': ts(h.joined_at)} for h in w.households]),
            'subscriptions.csv': csv_text(seed),
            f'day-{BUSINESS_DATE}.sql': '\n'.join(day) + '\n',
        }
    if part == 'billing':
        as_row = lambda c: {'charge_id': c.charge_id, 'household_id': c.household_id, 'kind': c.kind, 'reference': c.reference,
                            'amount': f'{c.amount:.2f}', 'status': c.status, 'posted_at': ts(c.posted_at), 'updated_at': ts(c.updated_at)}
        day = ['-- Billing\'s business day, 2026-10-31: every charge its application posted. Generated by',
               '-- sun_gen; applied before Course 5 lands dt=2026-10-31.', 'BEGIN;']
        for c in (c for c in w.charges if c.posted_at > SEED_CUTOFF):
            day.append(f'INSERT INTO charges VALUES ({", ".join(map(lit, as_row(c).values()))});')
        day.append('COMMIT;')
        rerate = ['-- 02:00:04 on 1 November: billing re-rates three of the night\'s rentals while the copy of',
                  '-- dt=2026-10-31 is running (§5.5). Generated by sun_gen.', 'BEGIN;']
        for cid in w.rerated:
            rerate.append(f"UPDATE charges SET amount = amount + ({RERATE_CREDIT}), status = 're-rated', "
                          f"updated_at = '{ts(RERATE_AT)}' WHERE charge_id = '{cid}';")
        rerate.append('COMMIT;')
        return {'charges.csv': csv_text([as_row(c) for c in w.charges if c.posted_at <= SEED_CUTOFF]),
                f'day-{BUSINESS_DATE}.sql': '\n'.join(day) + '\n', 'rerate.sql': '\n'.join(rerate) + '\n'}
    if part == 'catalogue':
        return {'titles.csv': csv_text(w.titles)}
    iso = lambda t: t.strftime('%Y-%m-%dT%H:%M:%SZ')
    guide = {'date': BUSINESS_DATE.isoformat(), 'provider': 'Sun EPG feed', 'channels': {}}
    for slot in w.epg:
        guide['channels'].setdefault(slot['channel'], []).append(
            {'start': iso(slot['start']), 'end': iso(slot['end']), 'title_id': slot['title_id']})
    return {f'{BUSINESS_DATE}.json': json.dumps(guide, indent=1) + '\n'}


def main(argv: list[str]) -> int:
    if argv[:1] == ['verify']:
        from .verify import verify
        return verify()
    p = argparse.ArgumentParser(prog='sun_gen')
    p.add_argument('--out', required=True, type=Path)
    p.add_argument('--part', choices=PARTS, action='append')
    a = p.parse_args(argv)
    for part in a.part or PARTS:
        for name, text in files(part).items():
            path = a.out / part / name
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
